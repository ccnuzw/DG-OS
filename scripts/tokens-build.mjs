import { readFileSync, writeFileSync } from 'node:fs';
import ts from 'typescript';

const seeds=JSON.parse(readFileSync(new URL('../src/ui/tokens/presets.json',import.meta.url),'utf8'));
const source=readFileSync(new URL('../src/ui/theme/kernel.ts',import.meta.url),'utf8').replace("import presetSeeds from '../tokens/presets.json';",`const presetSeeds=${JSON.stringify(seeds)};`);
const compiled=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.ESNext}}).outputText;
const {PRESET_IDS,resolveTheme}=await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);
let output='/* Generated by scripts/tokens-build.mjs; edit presets.json or theme/kernel.ts. */\n';
output+=`@theme static {\n${Object.entries(resolveTheme('studio','light')).filter(([key])=>key.startsWith('--color-')).map(([key,value])=>`  ${key}: ${value};`).join('\n')}\n}\n`;
for (const preset of PRESET_IDS) for (const mode of ['light','dark']) {
  const selectors=[`:root[data-preset="${preset}"][data-theme="${mode}"]`];
  if (preset==='studio') selectors.push(mode==='light' ? ':root:not([data-preset]):not([data-theme="dark"])' : ':root:not([data-preset])[data-theme="dark"]');
  output+=`${selectors.join(',\n')} {\n${Object.entries(resolveTheme(preset,mode)).map(([key,value])=>`  ${key}: ${value};`).join('\n')}\n}\n`;
}
const path=new URL('../src/ui/tokens/presets.css',import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(path,'utf8')!==output) throw new Error('Static theme tokens are stale; run npm run tokens:build');
  console.log('Static themes match the runtime kernel: five presets × light/dark.');
} else {
  writeFileSync(path,output);
  console.log('Generated five presets × light/dark from the runtime kernel.');
}
